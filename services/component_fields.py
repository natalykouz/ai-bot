def get_field_labels(module: str, element: str) -> list[str] | None:
    """Названия полей по порядку sample_text для этого компонента, либо None,
    если проверенной семантики нет (в т.ч. UNSAFE_ELEMENTS и любые модули без
    текстовых полей - Шапки/Подвалы/Изображения/Разделители/Мероприятия).
    При None вызывающий код обязан использовать старый режим ввода."""
    if (module, element) in UNSAFE_ELEMENTS:
        return None
    return FIELD_LABELS.get((module, element))


